# Year mentions we look for in questions
_YEAR_PATTERN = re.compile(r"\b(20\d\d)\b")

# Questions about future / unavailable years
_FUTURE_SIGNALS = [
    "2025", "2026", "next year", "forecast", "projection", "future", "predict"
]


def _normalize(text: str) -> str:
    return text.lower().strip()


class StructuredDataLookup:
    """
    Looks up validated financial figures from the disk cache produced by
    FinancialExtractor. Returns structured grounding facts for injection into
    the RAG prompt.
    """

    def __init__(self, cache_dir: Path = CACHE_DIR):
        self.cache_dir = cache_dir
        self._loaded: Dict[str, Dict[str, Any]] = {}

    def _load(self, doc_name: str) -> Optional[Dict[str, Any]]:
        stem = Path(doc_name).stem
        if stem in self._loaded:
            return self._loaded[stem]
        cache_file = self.cache_dir / f"{stem}_financials.json"
        if not cache_file.exists():
            return None
        try:
            data = json.loads(cache_file.read_text(encoding="utf-8"))
            self._loaded[stem] = data
            return data
        except Exception as e:
            print(f"[StructuredDataLookup] Failed to load cache for {doc_name}: {e}")
            return None

    def find_metric(
        self, question: str, doc_name: Optional[str]
    ) -> Optional[Dict[str, Any]]:
        """
        Try to match the question to a known financial metric in the cache.
        Returns a dict with 'grounding_text', 'source_citation', 'years_data'
        or None if no match / data unavailable.
        """
        if not doc_name:
            return None

        data = self._load(doc_name)
        if not data:
            return None

        q_lower = _normalize(question)

        # Check for explicit future-year signal → no data available
        for sig in _FUTURE_SIGNALS:
            if sig in q_lower:
                # Still try to match metric to give a useful abstention message
                pass  # handled below

        # Detect which years the question is asking about
        mentioned_years = _YEAR_PATTERN.findall(question)
        available_years = [str(y) for y in data.get("fiscal_years", [])]

        # Check if all mentioned years are outside our data
        future_years = [y for y in mentioned_years if y not in available_years]
        if mentioned_years and all(y not in available_years for y in mentioned_years):
            return {
                "grounding_text": (
                    f"IMPORTANT: The uploaded report covers fiscal years "
                    f"{', '.join(available_years)}. "
                    f"The year(s) {', '.join(mentioned_years)} are NOT reported in this filing. "
                    f"Do not fabricate figures for unreported years."
                ),
                "source_citation": f"Source: {doc_name} (fiscal years covered: {', '.join(available_years)})",
                "is_abstention": True,
                "years_data": {}
            }

        # Match metric
        matched_route = None
        for route in _METRIC_ROUTES:
            for kw in route["keywords"]:
                if kw in q_lower:
                    matched_route = route
                    break
            if matched_route:
                break

        if not matched_route:
            return None

        # Navigate the cache to get the metric data
        section, field = matched_route["path"]
        metric_data = data.get(section, {}).get(field, {})
        if not metric_data:
            return None

        source_citations = data.get("source_citations", {})
        source_label = source_citations.get(
            section.replace("income_statement", "income_statement")
                   .replace("balance_sheet", "balance_sheet")
                   .replace("cash_flows", "cash_flows"),
            f"{doc_name}"
        )
        # Map section keys to citation keys
        citation_key_map = {
            "income_statement": "income_statement",
            "balance_sheet": "balance_sheet",
            "cash_flows": "cash_flows",
        }
        source_label = source_citations.get(citation_key_map.get(section, ""), doc_name)

        company = data.get("company_name", "")
        currency = data.get("currency", "USD")
        unit = data.get("unit", "millions")
        label = matched_route["label"]
        per_share = matched_route.get("per_share", False)

        # Build grounding text for the years requested (or all available)
        target_years = mentioned_years if mentioned_years else available_years
        target_years = [y for y in target_years if y in metric_data]

        if not target_years:
            # Fall back to all available years in the metric
            target_years = sorted(metric_data.keys(), reverse=True)

        lines = []
        for y in target_years:
            val = metric_data.get(y)
            if val is None:
                lines.append(f"  FY {y}: NOT REPORTED in this filing")
            elif per_share:
                lines.append(f"  FY {y}: ${val:.2f} per diluted share")
            else:
                lines.append(f"  FY {y}: {currency} {val:,.0f} {unit}")

        # YoY growth calculation (Python arithmetic, not LLM)
        growth_lines = []
        sorted_target = sorted(target_years)
        for i in range(len(sorted_target) - 1):
            yr_curr = sorted_target[i + 1]
            yr_prev = sorted_target[i]
            val_curr = metric_data.get(yr_curr)
            val_prev = metric_data.get(yr_prev)
            if val_curr is not None and val_prev is not None and val_prev != 0:
                growth = ((val_curr - val_prev) / abs(val_prev)) * 100
                direction = "increase" if growth > 0 else "decrease"
                growth_lines.append(
                    f"  YoY change FY {yr_prev} → FY {yr_curr}: "
                    f"{growth:+.2f}% ({direction}) "
                    f"[Formula: ({val_curr:,.0f} - {val_prev:,.0f}) / {abs(val_prev):,.0f} × 100]"
                )

        grounding_parts = [
            f"VERIFIED FINANCIAL DATA — {company} — {label}",
            f"Source: {source_label}",
            f"Unit: {currency} {unit}" if not per_share else "Unit: USD per share",
            "",
        ] + lines

        if growth_lines:
            grounding_parts += ["", "Year-over-Year Change (Python-calculated):"] + growth_lines

        return {
            "grounding_text": "\n".join(grounding_parts),
            "source_citation": source_label,
            "is_abstention": False,
            "years_data": {y: metric_data.get(y) for y in target_years},
        }

    def get_all_cached_data(self) -> List[Dict[str, Any]]:
        """Loads all cached financial records from disk."""
        records = []
        for file in self.cache_dir.glob("*_financials.json"):
            stem = file.stem.replace("_financials", "")
            if stem not in self._loaded:
                try:
                    data = json.loads(file.read_text(encoding="utf-8"))
                    self._loaded[stem] = data
                except Exception as e:
                    print(f"[StructuredDataLookup] Failed to read {file.name}: {e}")
                    continue
            records.append(self._loaded[stem])
        return records

    def find_metrics_across_all(
        self, question: str
    ) -> Optional[Dict[str, Any]]:
        """
        Cross-company financial facts lookup across ALL cached filings.
        Supports:
        - Single company query within 'All Reports' mode (prioritizes that company)
        - Ranking questions ('highest revenue', 'most profitable', 'highest margin')
        - Comparison questions ('compare Apple and Tesla', 'revenue across all')
        - General cross-company KPI summaries
        """
        all_data = self.get_all_cached_data()
        if not all_data:
            return None

        q_lower = _normalize(question)

        # Detect any specific companies mentioned in question
        matched_companies = []
        for d in all_data:
            c_name = d.get("company_name", "").lower()
            src_doc = d.get("source_document", "").lower()
            stem = Path(src_doc).stem.lower().replace("_", " ").replace("-", " ")
            
            is_match = False
            if "apple" in q_lower and ("apple" in c_name or "apple" in src_doc):
                is_match = True
            elif "tesla" in q_lower and ("tesla" in c_name or "tesla" in src_doc):
                is_match = True
            elif "walmart" in q_lower and ("walmart" in c_name or "wmt" in src_doc):
                is_match = True
            elif "nvidia" in q_lower and ("nvidia" in c_name or "nvda" in src_doc):
                is_match = True
            elif "reliance" in q_lower and ("reliance" in c_name or "reliance" in src_doc):
                is_match = True
            else:
                name_words = [w for w in c_name.split() if len(w) > 3 and w not in ["corp", "inc.", "subsidiaries", "the", "company"]]
                if any(w in q_lower for w in name_words):
                    is_match = True

            if is_match and d not in matched_companies:
                matched_companies.append(d)

        # Check if question is a ranking, comparison, or global inquiry
        is_comparison_or_ranking = any(w in q_lower for w in [
            "highest", "lowest", "most", "least", "compare", "comparison", "rank", "ranking", 
            "across all", "all companies", "all reports", "between", "versus", "vs", "better", "best", "top"
        ])

        # If user asked about a single specific company (e.g. "What was Tesla's revenue?"):
        if len(matched_companies) == 1 and not is_comparison_or_ranking:
            primary_doc = matched_companies[0].get("source_document")
            res = self.find_metric(question, primary_doc)
            if res:
                c_name = matched_companies[0].get("company_name", "Company")
                res["grounding_text"] = f"[CROSS-FILING RAG TARGET: ALL REPORTS -> PRIORITIZING {c_name}]\n" + res["grounding_text"]
                return res

        # Determine target companies for comparison
        target_companies = matched_companies if (len(matched_companies) >= 2 and not any(w in q_lower for w in ["all", "highest", "lowest", "rank"])) else all_data

        # Detect metric from _METRIC_ROUTES
        matched_route = None
        for route in _METRIC_ROUTES:
            for kw in route["keywords"]:
                if kw in q_lower:
                    matched_route = route
                    break
            if matched_route:
                break

        # Helper to extract metric value for a company and year
        def get_metric_val(comp_data, year, route):
            sec, fld = route["path"]
            val = comp_data.get(sec, {}).get(fld, {}).get(year)
            # If FCF route and not directly stored, derive from operating_cf - abs(capex)
            if val is None and fld == "free_cash_flow":
                ocf = comp_data.get("cash_flows", {}).get("operating_cash_flow", {}).get(year)
                capex = comp_data.get("cash_flows", {}).get("capex", {}).get(year)
                if ocf is not None and capex is not None:
                    val = ocf - abs(capex)
            return val

        # Case 1: Specific metric matched (e.g., Total Revenue, Net Income, Operating Cash Flow)
        if matched_route:
            metric_label = matched_route["label"]
            rows = []
            timing_notes = []

            for comp in target_companies:
                c_name = comp.get("company_name", "Unknown")
                doc = comp.get("source_document", "SEC 10-K")
                curr = comp.get("currency", "USD")
                years = [str(y) for y in comp.get("fiscal_years", [])]
                latest_yr = years[0] if years else "N/A"
                val_latest = get_metric_val(comp, latest_yr, matched_route)

                # Format human readable
                if val_latest is not None:
                    abs_val = abs(val_latest)
                    sign = "-" if val_latest < 0 else ""
                    if matched_route.get("per_share"):
                        formatted_str = f"${val_latest:.2f}"
                    elif abs_val >= 1000:
                        formatted_str = f"{sign}${abs_val / 1000:.2f}B ({curr} {val_latest:,.0f}M)"
                    else:
                        formatted_str = f"{sign}${abs_val:.1f}M"
                else:
                    formatted_str = "Not Reported"

                # Check YoY change if previous year exists
                prev_yr = years[1] if len(years) > 1 else None
                val_prev = get_metric_val(comp, prev_yr, matched_route) if prev_yr else None
                yoy_str = "N/A"
                if val_latest is not None and val_prev is not None and val_prev != 0:
                    yoy = ((val_latest - val_prev) / abs(val_prev)) * 100
                    yoy_str = f"{yoy:+.2f}%"

                rows.append({
                    "name": c_name,
                    "doc": doc,
                    "latest_year": latest_yr,
                    "val": val_latest,
                    "formatted": formatted_str,
                    "yoy": yoy_str
                })
                timing_notes.append(f"{c_name}: FY {latest_yr} (Source: {doc})")

            # Sort descending by latest value if numeric
            sortable = [r for r in rows if r["val"] is not None]
            unsortable = [r for r in rows if r["val"] is None]
            sortable.sort(key=lambda x: x["val"], reverse=True)
            sorted_rows = sortable + unsortable

            # Build markdown table & summary
            lines = [
                f"=== VERIFIED CROSS-FILING FINANCIAL DATA: {metric_label.upper()} ===",
                f"Benchmark extracted across {len(sorted_rows)} audited annual reports in verified SEC 10-K cache.\n",
                f"| Rank | Company | Fiscal Year | {metric_label} | YoY Growth | Source Document |",
                f"|---|---|---|---:|---:|---|"
            ]
            for idx, r in enumerate(sorted_rows, 1):
                lines.append(f"| {idx} | {r['name']} | FY {r['latest_year']} | {r['formatted']} | {r['yoy']} | {r['doc']} |")

            lines.append("\n[Fiscal Timing & Reporting Dates]:")
            for t in timing_notes:
                lines.append(f"- {t}")
            lines.append("Note: Companies report on differing fiscal calendars. Interpret rankings with timing in mind.")
            lines.append("=== END VERIFIED CROSS-FILING DATA ===")

            return {
                "grounding_text": "\n".join(lines),
                "source_citation": f"Cross-Filing SEC 10-K Cache ({len(sorted_rows)} Companies)",
                "is_abstention": False,
                "years_data": {r["name"]: r["val"] for r in sorted_rows}
            }

        # Case 2: General comparative inquiry across multiple metrics (Revenue, Net Income, OCF, FCF)
        core_metrics = [
            ("total_revenue", "Total Revenue", ("income_statement", "total_revenue")),
            ("net_income", "Net Income", ("income_statement", "net_income")),
            ("operating_income", "Operating Income", ("income_statement", "operating_income")),
            ("operating_cash_flow", "Operating Cash Flow", ("cash_flows", "operating_cash_flow")),
        ]

        summary_lines = [
            "=== VERIFIED MULTI-COMPANY FINANCIAL BENCHMARK (SEC 10-K Cache) ===",
            "Audited figures for latest reported fiscal period:\n",
            "| Company | Fiscal Year | Revenue | Net Income | Operating CF | Source Filing |",
            "|---|---|---:|---:|---:|---|"
        ]

        for comp in target_companies:
            c_name = comp.get("company_name", "Unknown")
            doc = comp.get("source_document", "10-K")
            years = [str(y) for y in comp.get("fiscal_years", [])]
            latest_yr = years[0] if years else "N/A"

            def get_fmt(sec, fld):
                v = comp.get(sec, {}).get(fld, {}).get(latest_yr)
                if v is None: return "N/A"
                abs_v = abs(v)
                s = "-" if v < 0 else ""
                return f"{s}${abs_v / 1000:.2f}B" if abs_v >= 1000 else f"{s}${abs_v:.1f}M"

            rev_fmt = get_fmt("income_statement", "total_revenue")
            ni_fmt = get_fmt("income_statement", "net_income")
            ocf_fmt = get_fmt("cash_flows", "operating_cash_flow")

            summary_lines.append(f"| {c_name} | FY {latest_yr} | {rev_fmt} | {ni_fmt} | {ocf_fmt} | {doc} |")

        summary_lines.append("\n=== END VERIFIED MULTI-COMPANY BENCHMARK ===")

        return {
            "grounding_text": "\n".join(summary_lines),
            "source_citation": "Verified SEC 10-K Cross-Report Benchmark",
            "is_abstention": False,
            "years_data": {}
        }


# ---------------------------------------------------------------------------
# Junk chunk filter
# ---------------------------------------------------------------------------
_PAGE_FOOTER_PATTERN = re.compile(
    r"^[\w\s\.]+\|\s*20\d\d\s*Form\s*10-K\s*\|\s*\d+\s*$",
    re.IGNORECASE,
)

def _is_junk_chunk(text: str) -> bool:
    """Return True for page-footer-only or near-empty chunks."""
    stripped = text.strip()
    if len(stripped) < 80:
        return True
    if _PAGE_FOOTER_PATTERN.match(stripped):
        return True
    return False


