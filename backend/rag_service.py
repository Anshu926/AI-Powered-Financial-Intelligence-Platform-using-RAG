# RAGService
# ---------------------------------------------------------------------------
class RAGService:
    _instance = None

    def __init__(self):
        if not GEMINI_API_KEY:
            raise ValueError("GEMINI_API_KEY not found. Check your .env file.")

        print("[RAGService] Connecting to Gemini API...")
        self.gemini_client = genai.Client(
            api_key=GEMINI_API_KEY,
            http_options=types.HttpOptions(timeout=60000)
        )
        self.gemini_model = GEMINI_MODEL

        print(f"[RAGService] Loading embedding model ({EMBEDDING_MODEL_NAME})...")
        self.embedding_model = SentenceTransformer(EMBEDDING_MODEL_NAME)

        print(f"[RAGService] Connecting to ChromaDB at {CHROMA_DIR}...")
        self.chroma_client = chromadb.PersistentClient(path=str(CHROMA_DIR))

        try:
            self.collection = self.chroma_client.get_collection(name=DEFAULT_COLLECTION_NAME)
        except Exception:
            self.collection = self.chroma_client.get_or_create_collection(
                name=DEFAULT_COLLECTION_NAME,
                metadata={"hnsw:space": "cosine"}
            )
        print(
            f"[RAGService] Connected to collection '{self.collection.name}', "
            f"stored chunks: {self.collection.count()}"
        )

        self.structured_lookup = StructuredDataLookup()

    @classmethod
    def get_instance(cls) -> "RAGService":
        if cls._instance is None:
            cls._instance = RAGService()
        return cls._instance

    # ------------------------------------------------------------------
    # Vector Retrieval
    # ------------------------------------------------------------------
    def retrieve_chunks(
        self,
        question: str,
        top_k: int = 7,
        doc_filter: Optional[str] = None,
    ) -> List[Dict[str, Any]]:
        """
        Retrieve top_k chunks from ChromaDB.
        Requests top_k + 3 extra to allow junk filtering without losing results.
        """
        if self.collection.count() == 0:
            return []

        fetch_k = min(top_k + 4, self.collection.count())

        query_embedding = self.embedding_model.encode(
            question, normalize_embeddings=True
        ).tolist()

        query_args: Dict[str, Any] = {
            "query_embeddings": [query_embedding],
            "n_results": fetch_k,
            "include": ["documents", "metadatas", "distances"],
        }

        if doc_filter:
            query_args["where"] = {"source": doc_filter}

        try:
            results = self.collection.query(**query_args)
        except Exception as e:
            print(f"[RAGService] Filter query failed ({e}), running without filter...")
            query_args.pop("where", None)
            results = self.collection.query(**query_args)

        retrieved_chunks: List[Dict[str, Any]] = []
        if results and results.get("documents") and results["documents"][0]:
            documents = results["documents"][0]
            metadatas = results["metadatas"][0]
            distances = results["distances"][0]
            ids = results["ids"][0]

            for i, doc in enumerate(documents):
                meta = metadatas[i] if metadatas and i < len(metadatas) else {}
                dist = float(distances[i]) if distances and i < len(distances) else 0.0

                # Skip junk chunks (page footers, near-empty separators)
                if _is_junk_chunk(doc):
                    print(f"[RAGService] Skipping junk chunk {ids[i]} (len={len(doc)})")
                    continue

                retrieved_chunks.append({
                    "id": ids[i],
                    "text": doc,
                    "metadata": meta,
                    "distance": dist,
                })

                if len(retrieved_chunks) >= top_k:
                    break

        return retrieved_chunks

    # ------------------------------------------------------------------
    # Answer Generation
    # ------------------------------------------------------------------
    def generate_answer(
        self,
        question: str,
        retrieved_chunks: List[Dict[str, Any]],
        structured_fact: Optional[Dict[str, Any]] = None,
    ) -> str:
        """
        Generate answer using Gemini, optionally grounded in a structured fact
        block from the validated financial cache (structured_fact) plus retrieved
        vector chunks for citations and context.
        """
        # Build context blocks
        context_parts: List[str] = []

        # --- 1. Structured / validated data block (highest priority) ---
        if structured_fact:
            grounding = structured_fact.get("grounding_text", "")
            if grounding:
                context_parts.append(
                    "=== VERIFIED STRUCTURED FINANCIAL DATA (from validated SEC filing cache) ===\n"
                    + grounding
                    + "\n=== END VERIFIED DATA ==="
                )

            # If this is an abstention (future year / unavailable data), no
            # retrieved chunks context is needed; we still pass the chunks for
            # potential partial support.
            if structured_fact.get("is_abstention"):
                context_parts.append(
                    "[NOTE: The question references a year not covered by the "
                    "uploaded report. Clearly state this to the user and do NOT "
                    "fabricate figures.]"
                )

        # --- 2. Retrieved vector chunks ---
        if retrieved_chunks:
            chunk_parts = []
            for chunk in retrieved_chunks:
                meta = chunk.get("metadata", {})
                source = meta.get("source", "Unknown")
                chunk_index = meta.get("chunk_index", "?")
                page = meta.get("page_number", "")
                section = meta.get("section", "")
                loc = f"Chunk {chunk_index}"
                if page:
                    loc += f", Page {page}"
                if section:
                    loc += f", Section: {section}"
                chunk_parts.append(
                    f"[SOURCE: {source} | {loc}]\n{chunk.get('text', '')}"
                )
            context_parts.append(
                "=== RETRIEVED DOCUMENT PASSAGES ===\n"
                + "\n\n".join(chunk_parts)
                + "\n=== END RETRIEVED PASSAGES ==="
            )
        elif not structured_fact:
            return (
                "No relevant document passages were retrieved from the vector database "
                "to answer your question. Please ensure the annual report has been uploaded "
                "and indexed, then try rephrasing your question."
            )

        context = "\n\n".join(context_parts)

        # --- 3. Instruction prompt ---
        prompt = f"""You are an elite financial intelligence assistant for FinSight AI, specializing in SEC 10-K filings.
Your answers must look like a premium financial research analyst note: rigorous, polished, beautifully structured, and completely factual.

GROUNDING RULES:
1. VERIFIED STRUCTURED FINANCIAL DATA (labeled above) is authenticated from the validated SEC filing cache. Trust it 100% for exact figures — use it as your definitive benchmark.
2. RETRIEVED DOCUMENT PASSAGES provide supporting context, footnotes, segment breakdowns, and MD&A narrative.
3. NEVER invent, extrapolate, or hallucinate financial figures.
4. If a metric or year is explicitly flagged as NOT REPORTED or is a future year, state clearly in a polite, professional disclaimer that the requested information cannot be verified from the uploaded report. Do NOT substitute an estimate.

FORMATTING & PRESENTATION RULES:
1. FOR SIMPLE EXACT FIGURE QUESTIONS (e.g., net income, total assets, revenue):
   - State the primary figure boldly up front with the exact fiscal year, reporting scale (millions/billions), and currency (USD).
   - Follow with a concise 1-2 sentence breakdown naming the exact source statement (e.g., Consolidated Statements of Operations).
2. FOR MULTIPLE FIGURES OR COMPARISON QUESTIONS (e.g., 2022 vs 2023 vs 2024, or Products vs Services):
   - ALWAYS format the figures in a clean Markdown table with columns: `| Metric / Segment | FY 2024 | FY 2023 | FY 2022 | Source Statement |`.
   - Include a brief analytical takeaway below the table explaining YoY trends or growth drivers.
3. FOR WHY / HOW / EXPLANATORY QUESTIONS (e.g., tax rate increase, margins):
   - Use clear bold subheadings (e.g., **Key Drivers**, **Regulatory & Legal Impact**, **Financial Outcome**).
   - Use crisp, structured bullet points.
4. FOR RISK ANALYSIS QUESTIONS:
   - Break down each distinct category with bold headers (e.g., **1. Global Supply Chain Concentration**, **2. Foreign Exchange Fluctuations**).
   - Under each, provide a 1-sentence potential business impact.
5. MATHEMATICAL ACCURACY:
   - Present percentage changes and margins cleanly (e.g., `+2.02%` or `46.2%`), never exposing raw LaTeX code syntax.

6. CROSS-DOCUMENT & MULTI-COMPANY COMPARISON RULES:
   - When answering in All Reports mode or comparing multiple companies:
     a) CLEAR COMPANY ATTRIBUTION: Every financial figure must explicitly state the Company Name and Fiscal Year (e.g., "Apple Inc. (FY 2024): $391.04B", "Walmart (FY 2025): $680.99B", "Tesla, Inc. (FY 2024): $97.69B"). Never mix or combine values from different companies.
     b) RANKINGS & COMPARISONS: If the user asks who has the highest/lowest metric or to compare companies (e.g., "Which company has the highest revenue?"):
        - State the winner / ranking clearly up front.
        - Present the comparison in a clean Markdown table:
          | Rank | Company | Fiscal Year | Metric | Value | Source Filing |
        - Note any fiscal year timing discrepancies (e.g. Walmart reports on FY 2025 ending Jan 2025; Apple and Tesla report on FY 2024; NVIDIA report on file is FY 2022).
        - Provide brief analytical context explaining business models or scale differences.
     c) SINGLE-COMPANY INQUIRIES IN ALL-REPORTS MODE: If the user selects All Reports but asks about a single company (e.g., "What was Tesla's revenue?"):
        - Prioritize and answer for that specific company first using its verified audited filing.
        - You may provide brief comparative context with other peers (e.g. Apple or Walmart) only as secondary context.

CONTEXT:
{context}

USER QUESTION:
{question}

ANSWER:
"""

        response = self.gemini_client.models.generate_content(
            model=self.gemini_model,
            contents=prompt,
            config=types.GenerateContentConfig(
                temperature=0.1,
                max_output_tokens=1000,
            ),
        )

        if not response.text:
            return "The model returned an empty response. Please try rephrasing your question."

        return response.text.strip()

    # ------------------------------------------------------------------
    # Public query method
    # ------------------------------------------------------------------
    def query(
        self,
        question: str,
        top_k: int = 5,
        doc_filter: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        End-to-end RAG query.

        Pipeline:
        1. Structured data lookup (from financial cache) — fixes exact-figure failures
        2. Vector retrieval (ChromaDB) — with junk filtering
        3. Gemini generation — with structured fact + retrieved chunks
        4. Citation building — with page/section metadata when available
        """
        print(f"[RAGService] Query: '{question}' | filter: {doc_filter}")

        # Determine if query is in All Reports mode
        is_all_mode = False
        clean_filter = (doc_filter or "").strip().lower()
        if clean_filter in ["all", "all reports", "all_reports", "*"]:
            is_all_mode = True
            doc_filter = "all"
        elif not doc_filter:
            q_low = question.lower()
            if "tesla" in q_low:
                doc_filter = "2024_Tesla.pdf"
            elif "apple" in q_low:
                doc_filter = "Apple.pdf"
            elif "walmart" in q_low:
                doc_filter = "wmt-20250131.pdf"
            elif "nvidia" in q_low:
                doc_filter = "nvda-20220130.pdf"
            elif "reliance" in q_low:
                doc_filter = "Reliance.pdf"
            else:
                is_all_mode = True
                doc_filter = "all"

        if is_all_mode:
            print(f"[RAGService] Running cross-document query across ALL reports")
            # Step 1 — Cross-company structured data lookup
            structured_fact = self.structured_lookup.find_metrics_across_all(question)
            if structured_fact:
                print(f"[RAGService] Cross-company structured fact compiled: {structured_fact.get('source_citation')}")

            # Step 2 — Vector retrieval across ALL documents in ChromaDB (no where filter)
            chunks = self.retrieve_chunks(question, top_k=max(top_k, 8), doc_filter=None)
            print(f"[RAGService] Cross-filing retrieved {len(chunks)} chunks across all companies")
        else:
            print(f"[RAGService] Running targeted query for document: {doc_filter}")
            # Step 1 — Targeted structured data lookup
            structured_fact = self.structured_lookup.find_metric(question, doc_filter)
            if structured_fact:
                print(
                    f"[RAGService] Structured fact found: "
                    f"abstention={structured_fact.get('is_abstention')}"
                )

            # Step 2 — Vector retrieval filtered to document
            chunks = self.retrieve_chunks(question, top_k=top_k, doc_filter=doc_filter)
            print(f"[RAGService] Retrieved {len(chunks)} chunks after junk filtering")

        # Step 3 — Generate answer
        answer = self.generate_answer(question, chunks, structured_fact=structured_fact)

        # Step 4 — Build citations (only substantive chunks, not junk)
        citations = []

        # Add structured data as the first citation when available and not abstention
        if structured_fact and not structured_fact.get("is_abstention"):
            citations.append({
                "id": "structured_cache",
                "source": "All Reports (SEC 10-K Filings)" if is_all_mode else (doc_filter or "financial_cache"),
                "chunk_index": "validated-cache",
                "page_number": None,
                "section": structured_fact.get("source_citation") or ("Cross-Filing SEC 10-K Cache" if is_all_mode else "Verified Financial Cache (SEC 10-K)"),
                "distance": 0.0,
                "excerpt": structured_fact.get("grounding_text", "")[:500],
                "citation_type": "structured_cache",
            })

        for c in chunks:
            meta = c.get("metadata", {})
            text = c.get("text", "")
            excerpt = text[:400] + ("..." if len(text) > 400 else "")
            citations.append({
                "id": c["id"],
                "source": meta.get("source", "Unknown"),
                "chunk_index": meta.get("chunk_index", 0),
                "page_number": meta.get("page_number", None),
                "section": meta.get("section", None),
                "distance": round(c.get("distance", 0.0), 4),
                "excerpt": excerpt,
                "citation_type": "retrieved_chunk",
            })

        return {
            "question": question,
            "answer": answer,
            "sources": citations,
        }
